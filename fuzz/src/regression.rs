/// Decode call used when a corrupt failure exported its `.mut.bin` stream.
/// `input` in the generated test binds the mutated encoded stream.
enum CorruptDecode {
    /// `Result<Vec<u8>, _>`: also assert a bounded output size.
    Vec(&'static str),
    /// Any other decoder return type: panic-freedom is the assertion.
    Any(&'static str),
}

fn corrupt_vec_body(call: &str, limit: usize) -> String {
    format!(
        "    // `input` is the mutated encoded stream that triggered this fuzz\n    // failure; the decoder must return (Ok or Err) without panicking and\n    // without unbounded output.\n    let decoded = {call};\n    if let Ok(bytes) = decoded {{\n        assert!(bytes.len() <= {limit}, \"corrupt decode produced {{}} bytes\", bytes.len());\n    }}"
    )
}

fn corrupt_any_body(call: &str) -> String {
    format!(
        "    // `input` is the mutated encoded stream that triggered this fuzz\n    // failure; the decoder must return (Ok or Err) without panicking.\n    let _ = {call};"
    )
}

