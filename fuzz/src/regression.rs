fn roundtrip_body(encode_expr: &str, decode_expr: &str) -> String {
    format!(
        "    let encoded = {encode_expr};\n    let decoded = {decode_expr};\n    assert_eq!(decoded, input);"
    )
}

fn archive_roundtrip_body(encoder_init: &str, decode_expr: &str) -> String {
    format!(
        "    {encoder_init}\n    enc.add_file(\"fuzz_test\", input);\n    let encoded = enc.finish().unwrap();\n    {decode_expr}\n    assert_eq!(entries[0].data, input);"
    )
}

fn zip_options_roundtrip_body(compression: &str) -> String {
    format!(
        "    let mut enc = archive::archive::zip::encode::ZipEncoder::new();\n    enc.add_file_with_options(\"fuzz_test\", input, &archive::archive::zip::encode::ZipEntryOptions {{ compression: archive::archive::zip::encode::ZipCompression::{compression}, ..Default::default() }});\n    let encoded = enc.finish().unwrap();\n    let entries = archive::archive::zip::decode::decode(&encoded).unwrap();\n    assert_eq!(entries[0].data, input);"
    )
}

fn integration_pattern_body(algo: Algorithm, pattern: TestPattern) -> String {
    format!(
        "    // Exported from fuzz failure for {algo} / {pattern}.\n    // This pattern needs a system tool or integration helper.\n    // Suggested next step: replace this placeholder with a direct external-tool regression.\n    panic!(\"fill in external-tool regression using this fixture\");"
    )
}

fn sanitize(input: &str) -> String {
    input
        .chars()
        .map(|ch| match ch {
            'a'..='z' | 'A'..='Z' | '0'..='9' | '-' | '_' => ch,
            _ => '-',
        })
        .collect()
}

fn sanitize_for_module(input: &str) -> String {
    sanitize(input).replace('-', "_")
}

#[cfg(test)]
mod tests {
    use super::{template_for, update_generated_mod};
    use crate::algorithms::Algorithm;
    use crate::report::TestPattern;
    #[test]
    fn self_template_mentions_codec_calls() {
        let rendered = template_for(Algorithm::Gzip, TestPattern::Self_, "fixture.bin");
        assert!(rendered.contains("archive::compress::gzip::encode::encode"));
        assert!(rendered.contains("assert_eq!(decoded, input)"));
    }

    #[test]
    fn generated_mod_dedupes_entries() {
        let dir = tempfile::tempdir().unwrap();
        let mod_path = dir.path().join("mod.rs");
        update_generated_mod(&mod_path, "case_one").unwrap();
        update_generated_mod(&mod_path, "case_one").unwrap();
        let content = std::fs::read_to_string(&mod_path).unwrap();
        assert_eq!(content.matches("mod case_one;").count(), 1);
    }
}
