use crate::algorithms::Algorithm;
use crate::report::{self, TestPattern};
use std::fs;
use std::path::{Path, PathBuf};

const DEFAULT_FIXTURE_DIR: &str = "tests/fixtures/fuzz/generated";
const DEFAULT_TEST_DIR: &str = "tests/integration/generated";
const GENERATED_MOD_HEADER: &str = "// Generated by archive-fuzz --import-regression.\n";

pub fn export_failure(artifact: &Path, out_dir: &Path) -> Result<(PathBuf, PathBuf), String> {
    let exported = prepare_export(artifact, out_dir)?;
    // The template is written next to the fixtures; use a bare filename so
    // `include_bytes!` resolves regardless of how `--regression-dir` was
    // spelled.
    let fixture_literal = if exported.mutated_fixture_path.is_some() {
        format!("{}.mut.bin", exported.base)
    } else {
        format!("{}.bin", exported.base)
    };
    fs::write(
        &exported.template_path,
        template_for(
            exported.algo,
            exported.pattern,
            &fixture_literal,
            exported.mutated_fixture_path.is_some(),
            exported.corrupt_limit,
        ),
    )
    .map_err(|e| format!("write template failed: {e}"))?;

    Ok((exported.fixture_path, exported.template_path))
}

pub fn import_failure(
    artifact: &Path,
    repo_root: &Path,
) -> Result<(PathBuf, PathBuf, PathBuf), String> {
    let fixture_dir = repo_root.join(DEFAULT_FIXTURE_DIR);
    let test_dir = repo_root.join(DEFAULT_TEST_DIR);
    let exported = prepare_export(artifact, &fixture_dir)?;

    fs::create_dir_all(&test_dir).map_err(|e| format!("create generated test dir failed: {e}"))?;

    let module_name = sanitize_for_module(&exported.base);
    let test_path = test_dir.join(format!("{module_name}.rs"));
    // For corrupt failures the mutated stream is the reproducer: point the
    // generated test at the `.mut.bin` sidecar when it was exported.
    let fixture_literal = if exported.mutated_fixture_path.is_some() {
        format!("../../fixtures/fuzz/generated/{}.mut.bin", exported.base)
    } else {
        format!("../../fixtures/fuzz/generated/{}.bin", exported.base)
    };
    fs::write(
        &test_path,
        template_for(
            exported.algo,
            exported.pattern,
            &fixture_literal,
            exported.mutated_fixture_path.is_some(),
            exported.corrupt_limit,
        ),
    )
    .map_err(|e| format!("write generated test failed: {e}"))?;

    let mod_path = test_dir.join("mod.rs");
    update_generated_mod(&mod_path, &module_name)?;

    Ok((exported.fixture_path, test_path, mod_path))
}

struct PreparedExport {
    algo: Algorithm,
    pattern: TestPattern,
    base: String,
    fixture_path: PathBuf,
    mutated_fixture_path: Option<PathBuf>,
    template_path: PathBuf,
    corrupt_limit: usize,
}

fn prepare_export(artifact: &Path, out_dir: &Path) -> Result<PreparedExport, String> {
    let loaded = report::load_failure(artifact)?;
    let algo = Algorithm::from_name(&loaded.report.algorithm).ok_or_else(|| {
        format!(
            "unknown algorithm in failure report: {}",
            loaded.report.algorithm
        )
    })?;
    let pattern = TestPattern::from_label(&loaded.report.pattern).ok_or_else(|| {
        format!(
            "unknown pattern in failure report: {}",
            loaded.report.pattern
        )
    })?;

    fs::create_dir_all(out_dir).map_err(|e| format!("create regression dir failed: {e}"))?;

    let signature = if loaded.report.signature.is_empty() {
        report::failure_signature(algo, pattern, &loaded.report.error)
    } else {
        loaded.report.signature.clone()
    };
    let mut base = format!(
        "{}_{}_{}",
        sanitize(algo.name()),
        sanitize(pattern.label()),
        sanitize(&signature.chars().take(24).collect::<String>())
    );
    // The signature is `algo|pattern|error`, so its first 24 chars can be
    // entirely consumed by the algo/pattern prefix; distinct failures then
    // collide on `base` and a second import silently overwrites the first
    // fixture. Disambiguate with the input data hash.
    if !loaded.report.data_blake3.is_empty() {
        let tag_len = loaded.report.data_blake3.len().min(8);
        base.push('_');
        base.push_str(&loaded.report.data_blake3[..tag_len]);
    }

    // Corrupt failures carry the failing mutated encoded stream in a
    // `.mut.bin` sidecar. Read it before writing anything so a missing
    // sidecar aborts the export without leaving a half-populated fixture.
    let mutated_bytes = match &loaded.report.mut_file {
        Some(mut_file) => {
            let src = artifact
                .parent()
                .unwrap_or_else(|| Path::new("."))
                .join(mut_file);
            Some(
                fs::read(&src)
                    .map_err(|e| format!("read mutated stream {} failed: {e}", src.display()))?,
            )
        }
        None => None,
    };

    let fixture_path = out_dir.join(format!("{base}.bin"));
    fs::write(&fixture_path, &loaded.data).map_err(|e| format!("write fixture failed: {e}"))?;
    let mutated_fixture_path = match mutated_bytes {
        Some(bytes) => {
            let dst = out_dir.join(format!("{base}.mut.bin"));
            fs::write(&dst, &bytes).map_err(|e| format!("write mutated fixture failed: {e}"))?;
            Some(dst)
        }
        None => None,
    };

    let corrupt_limit =
        crate::runner::corrupt_decoded_limit(loaded.report.original_size.max(loaded.data.len()));
    let template_path = out_dir.join(format!("{base}.rs"));
    Ok(PreparedExport {
        algo,
        pattern,
        base,
        fixture_path,
        mutated_fixture_path,
        template_path,
        corrupt_limit,
    })
}

fn update_generated_mod(path: &Path, module_name: &str) -> Result<(), String> {
    let mut content = if path.exists() {
        fs::read_to_string(path).map_err(|e| format!("read generated mod failed: {e}"))?
    } else {
        GENERATED_MOD_HEADER.to_string()
    };

    let line = format!("mod {module_name};\n");
    if !content.contains(&line) {
        if !content.ends_with('\n') {
            content.push('\n');
        }
        content.push_str(&line);
    }

    fs::write(path, content).map_err(|e| format!("write generated mod failed: {e}"))
}

fn template_for(
    algo: Algorithm,
    pattern: TestPattern,
    fixture_literal: &str,
    has_mutated_stream: bool,
    corrupt_limit: usize,
) -> String {
    let fn_name = format!(
        "test_fuzz_regression_{}_{}",
        sanitize_for_module(algo.name()),
        sanitize_for_module(pattern.label())
    );
    let mut attrs = format!("#[cfg(feature = \"{}\")]\n", feature_gate_for(algo));
    let corrupt_body = has_mutated_stream
        .then(|| corrupt_body_for(algo, corrupt_limit))
        .flatten();
    match pattern {
        TestPattern::OriginalCompress | TestPattern::OriginalDecompress => {
            attrs.push_str("#[ignore = \"fill in external-tool regression using this fixture\"]\n");
        }
        // Without an exported `.mut.bin` the fixture stores the original
        // (pre-encode) input, not the mutated stream that triggered the
        // failure, so a generated test cannot replay the corrupt path.
        TestPattern::Corrupt if corrupt_body.is_none() => {
            attrs.push_str(
                "#[ignore = \"fill in corrupt-input regression: re-encode this fixture and mutate the encoded stream\"]\n",
            );
        }
        TestPattern::Corrupt | TestPattern::Self_ => {}
    }
    let body = match pattern {
        TestPattern::Self_ => self_pattern_body(algo),
        TestPattern::Corrupt => corrupt_body.unwrap_or_else(|| corrupt_pattern_body(algo, pattern)),
        TestPattern::OriginalCompress | TestPattern::OriginalDecompress => {
            integration_pattern_body(algo, pattern)
        }
    };

    format!(
        "{attrs}#[test]\nfn {fn_name}() {{\n    let input = include_bytes!(\"{fixture_literal}\");\n{body}\n}}\n"
    )
}

