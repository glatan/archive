#[test]
fn zx1_reference_vector_text() {
    let dec = zx1::decode(ZX1_FOX).unwrap();
    assert_eq!(
        dec,
        b"the quick brown fox jumps over the lazy dog. the quick brown fox.\n"
    );
}

#[test]
fn zx1_reference_vector_rep_offset() {
    // 299 'a' + NUL: exercises copy-from-last-offset.
    let mut expected = vec![b'a'; 299];
    expected.push(0);
    let dec = zx1::decode(ZX1_A300).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx1_reference_vector_long_match() {
    // 4100 bytes: a 20-byte literal run followed by a long match chain.
    let pat = b"the quick brown fox ";
    let mut expected = Vec::new();
    for _ in 0..205 {
        expected.extend_from_slice(pat);
    }
    let dec = zx1::decode(ZX1_T4K).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx1_reference_vector_mixed() {
    // 2388 bytes: 8x 0x00..=0xFF literal+match mix, then a "hello hello hello"
    // rep-offset tail. Exercises interleaved literal and match blocks.
    let mut expected = Vec::new();
    for _ in 0..8 {
        expected.extend(0u8..=255);
    }
    for _ in 0..20 {
        expected.extend_from_slice(b"hello hello hello");
    }
    let dec = zx1::decode(ZX1_MIX).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx1_reference_vector_far_offset() {
    // 1400 bytes: 200 'A' + (0x00..=0xFA)*4 truncated to 1000 + 200 'A'.
    // Exercises the two-byte (far) offset form.
    let mut expected = vec![b'A'; 200];
    let seg: Vec<u8> = (0u8..=250).collect();
    for _ in 0..4 {
        expected.extend_from_slice(&seg);
    }
    expected.truncate(1200);
    expected.extend_from_slice(&[b'A'; 200]);
    assert_eq!(expected.len(), 1400);
    let dec = zx1::decode(ZX1_FAR).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx1_roundtrips() {
    let mut cases: Vec<Vec<u8>> = vec![
        Vec::new(),
        b"x".to_vec(),
        b"ab".to_vec(),
        b"hello hello hello".to_vec(),
        vec![0u8; 3000],
    ];
    let mut text = Vec::new();
    for _ in 0..200 {
        text.extend_from_slice(b"the quick brown fox jumps over the lazy dog. ");
    }
    cases.push(text);
    let mut binary = Vec::new();
    for i in 0..30000u32 {
        binary.extend_from_slice(&i.to_le_bytes());
    }
    cases.push(binary);
    // mixed runs to exercise copy-from-last-offset paths
    let mut mixed = Vec::new();
    for _ in 0..80 {
        mixed.extend_from_slice(b"aaaaa");
        mixed.extend_from_slice(b"bcdefg");
    }
    cases.push(mixed);

    for data in &cases {
        assert_eq!(&zx1::decode(&zx1::encode(data)).unwrap(), data);
    }
}

#[test]
fn zx1_rejects_malformed() {
    assert!(zx1::decode(&[0x80]).is_err()); // literal len but no data
    assert!(zx1::decode(&[0xf2, 0xf8]).is_err()); // truncated literals
    // trailing garbage after EOF
    let mut c = ZX1_FOX.to_vec();
    c.push(0xaa);
    assert!(zx1::decode(&c).is_err());
}

