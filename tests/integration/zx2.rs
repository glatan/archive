#[test]
fn zx2_reference_vector_text() {
    let dec = zx2::decode(ZX2_FOX).unwrap();
    assert_eq!(
        dec,
        b"the quick brown fox jumps over the lazy dog. the quick brown fox.\n"
    );
}

#[test]
fn zx2_reference_vector_rep_offset() {
    // 299 'a' + NUL: exercises copy-from-last-offset.
    let mut expected = vec![b'a'; 299];
    expected.push(0);
    let dec = zx2::decode(ZX2_A300).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx2_reference_vector_long_match() {
    // 4100 bytes: a 20-byte literal run followed by a long match chain.
    let pat = b"the quick brown fox ";
    let mut expected = Vec::new();
    for _ in 0..205 {
        expected.extend_from_slice(pat);
    }
    let dec = zx2::decode(ZX2_T4K).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx2_reference_vector_mixed() {
    // 570 bytes: 4x 0x00..=0x63 (rep-offset matches at distance 100),
    // then a "hello hello hello" tail. Exercises interleaved literal
    // and match blocks.
    let mut expected = Vec::new();
    for _ in 0..4 {
        expected.extend(0u8..=99);
    }
    for _ in 0..10 {
        expected.extend_from_slice(b"hello hello hello");
    }
    let dec = zx2::decode(ZX2_MIX).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx2_reference_vector_far_offset() {
    // 375 bytes: 0x00..=0xFE (255 literals) + repeat of first 20 bytes
    // at offset 255 (the format limit) + 100 'Z'.
    let mut expected: Vec<u8> = (0u8..=254).collect();
    expected.extend(0u8..20);
    expected.extend_from_slice(&[b'Z'; 100]);
    assert_eq!(expected.len(), 375);
    let dec = zx2::decode(ZX2_FAR).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn zx2_roundtrips() {
    let mut cases: Vec<Vec<u8>> = vec![
        Vec::new(),
        b"x".to_vec(),
        b"ab".to_vec(),
        b"hello hello hello".to_vec(),
        vec![0u8; 3000],
    ];
    let mut text = Vec::new();
    for _ in 0..200 {
        text.extend_from_slice(b"the quick brown fox jumps over the lazy dog. ");
    }
    cases.push(text);
    let mut binary = Vec::new();
    for i in 0..30000u32 {
        binary.extend_from_slice(&i.to_le_bytes());
    }
    cases.push(binary);
    // mixed runs to exercise copy-from-last-offset paths
    let mut mixed = Vec::new();
    for _ in 0..80 {
        mixed.extend_from_slice(b"aaaaa");
        mixed.extend_from_slice(b"bcdefg");
    }
    cases.push(mixed);

    for data in &cases {
        assert_eq!(&zx2::decode(&zx2::encode(data)).unwrap(), data);
    }
}

#[test]
fn zx2_rejects_malformed() {
    assert!(zx2::decode(&[0x80]).is_err()); // literal len but no data
    assert!(zx2::decode(&[0xf2, 0xf8]).is_err()); // truncated literals
    // trailing garbage after EOF
    let mut c = ZX2_FOX.to_vec();
    c.push(0xaa);
    assert!(zx2::decode(&c).is_err());
}

