fn lzrw1a_expected_text4k() -> Vec<u8> {
    let pat = b"the quick brown fox ";
    (0..4096).map(|i| pat[i % 20]).collect()
}

#[test]
fn lzrw1a_reference_vector_verbatim() {
    // Reference encoder chose the verbatim copy flag for this input.
    let dec = lzrw1a::decode(VEC_FOX).unwrap();
    assert_eq!(
        dec,
        b"the quick brown fox jumps over the lazy dog. the quick brown fox."
    );
}

#[test]
fn lzrw1a_reference_vector_compressed() {
    // Mixed literal/copy items, dense control bits and a partial last
    // group with trailing literals.
    let mut expected = vec![b'a'; 299];
    expected.push(0);
    let dec = lzrw1a::decode(VEC_A300).unwrap();
    assert_eq!(dec, expected);
}

#[test]
fn lzrw1a_reference_vector_max_offset() {
    // Many copy items including len-18 copies at the maximum offset 4095
    // (0xf0 0xff) interleaved with literals.
    let dec = lzrw1a::decode(VEC_TEXT4K).unwrap();
    assert_eq!(dec, lzrw1a_expected_text4k());
}

#[test]
fn lzrw1a_hand_built() {
    // flag + control 0x0008 (item 3 is copy) + 3 literals + copy item.
    let input = [0, 0, 0, 0, 0x08, 0x00, b'a', b'b', b'c', 0x03, 0x03];
    assert_eq!(lzrw1a::decode(&input).unwrap(), b"abcabcabc");
}

#[test]
fn lzrw1a_roundtrips() {
    let mut cases: Vec<Vec<u8>> = vec![
        Vec::new(),
        b"x".to_vec(),
        b"hello hello hello hello".to_vec(),
        vec![0u8; 3000],
    ];
    let mut text = Vec::new();
    for _ in 0..200 {
        text.extend_from_slice(b"the quick brown fox jumps over the lazy dog. ");
    }
    cases.push(text);
    let mut binary = Vec::new();
    for i in 0..30000u32 {
        binary.extend_from_slice(&i.to_le_bytes());
    }
    cases.push(binary);
    let mut noise = Vec::with_capacity(2048);
    let mut x = 0x9e3779b9u32;
    for _ in 0..2048 {
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        noise.push((x >> 24) as u8);
    }
    cases.push(noise); // exercises the verbatim copy flag

    for data in &cases {
        assert_eq!(&lzrw1a::decode(&lzrw1a::encode(data)).unwrap(), data);
    }
}

#[test]
fn lzrw1a_rejects_malformed() {
    assert!(lzrw1a::decode(&[0, 0]).is_err()); // truncated flag
    assert!(lzrw1a::decode(&[7, 0, 0, 0, 1, 2, 3]).is_err()); // bad flag
    // copy item with offset 0
    assert!(lzrw1a::decode(&[0, 0, 0, 0, 0x01, 0x00, 0x00, 0x00]).is_err());
    // copy item truncated mid-item
    assert!(lzrw1a::decode(&[0, 0, 0, 0, 0x01, 0x00, 0x00]).is_err());
}
