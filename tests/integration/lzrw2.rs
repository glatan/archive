#[test]
fn lzrw2_reference_vector_fox() {
    let dec = lzrw2::decode(VEC_FOX).unwrap();
    assert_eq!(
        dec,
        (b"the quick brown fox jumps over the lazy dog. ".repeat(6))[..260].to_vec()
    );
}

#[test]
fn lzrw2_reference_vector_a300() {
    let dec = lzrw2::decode(VEC_A300).unwrap();
    assert_eq!(dec, vec![b'a'; 300]);
}

#[test]
fn lzrw2_reference_vector_startstr() {
    let dec = lzrw2::decode(VEC_STARTSTR).unwrap();
    assert_eq!(dec, b"123456789012345678 ".repeat(12));
}

#[test]
fn lzrw2_reference_vector_binary() {
    let dec = lzrw2::decode(VEC_BINARY).unwrap();
    assert_eq!(
        dec,
        (0..120u32)
            .flat_map(|i| i.to_le_bytes())
            .collect::<Vec<u8>>()
    );
}

#[test]
fn lzrw2_reference_vector_mixed() {
    let dec = lzrw2::decode(VEC_MIXED).unwrap();
    assert_eq!(dec, {
        let mut v = b"0123456789abcdefg ".to_vec();
        v.extend_from_slice(&b"abc".repeat(40));
        v.extend_from_slice(b" 0123456789abcdefg");
        v.extend(0u8..64);
        v
    });
}

#[test]
fn lzrw2_reference_vector_noise() {
    let dec = lzrw2::decode(VEC_NOISE).unwrap();
    assert_eq!(dec, {
        let mut v = Vec::new();
        let mut x = 0x9e3779b9u32;
        for _ in 0..300 {
            x ^= x << 13;
            x ^= x >> 17;
            x ^= x << 5;
            v.push((x >> 24) as u8);
        }
        v
    });
}

#[test]
fn lzrw2_roundtrips() {
    let mut cases: Vec<Vec<u8>> = vec![
        Vec::new(),
        b"x".to_vec(),
        b"hello hello hello hello".to_vec(),
        vec![0u8; 3000],
    ];
    let mut text = Vec::new();
    for _ in 0..200 {
        text.extend_from_slice(b"the quick brown fox jumps over the lazy dog. ");
    }
    cases.push(text);
    let mut binary = Vec::new();
    for i in 0..30000u32 {
        binary.extend_from_slice(&i.to_le_bytes());
    }
    cases.push(binary);
    let mut noise = Vec::with_capacity(2048);
    let mut x = 0x9e3779b9u32;
    for _ in 0..2048 {
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        noise.push((x >> 24) as u8);
    }
    cases.push(noise); // exercises the verbatim copy flag

    for data in &cases {
        assert_eq!(&lzrw2::decode(&lzrw2::encode(data)).unwrap(), data);
    }
}

#[test]
fn lzrw2_rejects_malformed() {
    assert!(lzrw2::decode(&[0, 0]).is_err()); // truncated flag
    assert!(lzrw2::decode(&[7, 0, 0, 0, 1, 2, 3]).is_err()); // bad flag
    // copy item referencing a never-written phrase entry
    assert!(lzrw2::decode(&[0, 0, 0, 0, 0x01, 0x00, 0x02, 0x05]).is_err());
    // copy item truncated mid-item
    assert!(lzrw2::decode(&[0, 0, 0, 0, 0x01, 0x00, 0x00]).is_err());
}
